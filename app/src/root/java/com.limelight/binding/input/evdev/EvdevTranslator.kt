    @JvmStatic
    fun translateEvdevKeyCode(evdevKeyCode: Short): Short {
        return if (evdevKeyCode >= 0 && evdevKeyCode < EVDEV_KEY_CODES.size) {
            EVDEV_KEY_CODES[evdevKeyCode.toInt()]
        } else {
            0
        }
    }
